export function searchVerifiedFoods(
  query: string,
  dietaryFilter?: DietaryPreference
): VerifiedFoodItem[] {
  const q = query.trim().toLowerCase();
  return VERIFIED_FOOD_DATABASE.filter((item) => {
    if (dietaryFilter && !item.dietaryTags.includes(dietaryFilter)) {
      return false;
    }
    if (!q) return true;
    if (item.name.toLowerCase().includes(q)) return true;
    if (item.category.toLowerCase().includes(q)) return true;
    if (item.aliases?.some((a) => a.toLowerCase().includes(q))) return true;
    return false;
  });
}
